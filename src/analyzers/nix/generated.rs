use std::path::Path;

const GENERATORS: [&str; 6] = [
    "node2nix",
    "crate2nix",
    "gomod2nix",
    "yarn2nix",
    "poetry2nix",
    "cabal2nix",
];

const GENERATED_FILENAMES: [&str; 3] = ["node-packages.nix", "node-env.nix", "Cargo.nix"];

pub fn is_generated_nix(path: &Path, source: &str) -> bool {
    has_generated_comment(source) || has_generated_filename(path)
}

fn has_generated_comment(source: &str) -> bool {
    source
        .lines()
        .take(10)
        .map(str::to_lowercase)
        .any(|line| is_generated_line(&line))
}

fn is_generated_line(line: &str) -> bool {
    line.contains("this file was automatically generated")
        || line.contains("do not edit")
        || (line.contains("generated by") && GENERATORS.iter().any(|tool| line.contains(tool)))
}

fn has_generated_filename(path: &Path) -> bool {
    path.file_name()
        .and_then(|name| name.to_str())
        .is_some_and(|name| GENERATED_FILENAMES.contains(&name))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_generator_comment() {
        let source = "# This file has been generated by node2nix 1.11.1. Do not edit!\n{}";
        assert!(is_generated_nix(Path::new("x.nix"), source));
    }

    #[test]
    fn test_automatically_generated_comment() {
        let source = "# This file was automatically generated\n{}";
        assert!(is_generated_nix(Path::new("x.nix"), source));
    }

    #[test]
    fn test_generated_filenames() {
        assert!(is_generated_nix(Path::new("node-packages.nix"), "{}"));
        assert!(is_generated_nix(Path::new("node-env.nix"), "{}"));
        assert!(is_generated_nix(Path::new("Cargo.nix"), "{}"));
    }

    #[test]
    fn test_marker_beyond_header_ignored() {
        let source = format!("{}# generated by node2nix\n", "{}\n".repeat(10));
        assert!(!is_generated_nix(Path::new("x.nix"), &source));
    }

    #[test]
    fn test_regular_nix_file() {
        assert!(!is_generated_nix(Path::new("default.nix"), "{ lib }: lib"));
    }
}
