//! Nix analyzer implementation.

use crate::analyzers::Analyzer;
use crate::analyzers::nix::orchestration::analyze_nix_file_with_mode;
use crate::analyzers::nix::parser::parse_source;
use crate::config::GeneratedCodeMode;
use crate::core::ast::Ast;
use crate::core::{ComplexityMetrics, FileMetrics, Language};
use anyhow::Result;
use std::path::PathBuf;

pub struct NixAnalyzer {
    complexity_threshold: u32,
    generated_code_mode: GeneratedCodeMode,
}

impl NixAnalyzer {
    pub fn new() -> Self {
        Self {
            complexity_threshold: 10,
            generated_code_mode: GeneratedCodeMode::SuppressDebt,
        }
    }

    pub fn with_threshold(mut self, threshold: u32) -> Self {
        self.complexity_threshold = threshold;
        self
    }

    pub fn with_generated_code_mode(mut self, mode: GeneratedCodeMode) -> Self {
        self.generated_code_mode = mode;
        self
    }
}

impl Default for NixAnalyzer {
    fn default() -> Self {
        Self::new()
    }
}

impl Analyzer for NixAnalyzer {
    fn parse(&self, content: &str, path: PathBuf) -> Result<Ast> {
        Ok(Ast::Nix(parse_source(content, &path)?))
    }

    fn analyze(&self, ast: &Ast) -> FileMetrics {
        match ast {
            Ast::Nix(nix_ast) => analyze_nix_file_with_mode(
                nix_ast,
                self.complexity_threshold,
                self.generated_code_mode,
            ),
            _ => empty_nix_metrics(),
        }
    }

    fn language(&self) -> Language {
        Language::Nix
    }
}

fn empty_nix_metrics() -> FileMetrics {
    FileMetrics {
        path: PathBuf::new(),
        language: Language::Nix,
        complexity: ComplexityMetrics::default(),
        debt_items: vec![],
        dependencies: vec![],
        duplications: vec![],
        total_lines: 0,
        test_lines: 0,
        module_scope: None,
        classes: None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::analyzers::get_analyzer;

    const FLAKE: &str = r#"{
  inputs.nixpkgs.url = "github:NixOS/nixpkgs";
  outputs = { self, nixpkgs }:
    let mk = x: if x then 1 else 2; in {
      packages.default = mk true;
    };
}
"#;

    fn analyze(analyzer: &NixAnalyzer, source: &str, path: &str) -> FileMetrics {
        let ast = analyzer.parse(source, PathBuf::from(path)).unwrap();
        analyzer.analyze(&ast)
    }

    #[test]
    fn test_nix_analyzer_language_and_factory() {
        assert_eq!(NixAnalyzer::new().language(), Language::Nix);
        assert_eq!(get_analyzer(Language::Nix).language(), Language::Nix);
    }

    #[test]
    fn test_end_to_end_via_factory() {
        let analyzer = get_analyzer(Language::Nix);
        let ast = analyzer.parse(FLAKE, PathBuf::from("flake.nix")).unwrap();
        let metrics = analyzer.analyze(&ast);
        let names: Vec<_> = metrics
            .complexity
            .functions
            .iter()
            .map(|f| f.name.as_str())
            .collect();

        assert_eq!(metrics.language, Language::Nix);
        assert_eq!(names, vec!["outputs", "outputs.mk"]);
        assert_eq!(metrics.dependencies[0].name, "github:NixOS/nixpkgs");
        assert_eq!(metrics.total_lines, 7);
    }

    #[test]
    fn test_complexity_debt_above_threshold() {
        let source = "{ f = a: b: if a || b then (if a then 1 else 2) else 3; }";
        let metrics = analyze(&NixAnalyzer::new().with_threshold(2), source, "x.nix");

        assert!(metrics.complexity.functions[0].cyclomatic > 2);
        assert!(!metrics.debt_items.is_empty());
    }

    #[test]
    fn test_no_debt_below_threshold() {
        let metrics = analyze(
            &NixAnalyzer::new(),
            "{ f = a: if a then 1 else 2; }",
            "x.nix",
        );
        assert!(metrics.debt_items.is_empty());
    }

    #[test]
    fn test_test_function_skips_debt() {
        let source = "{ checks.smoke = a: if a then 1 else 2; }";
        let metrics = analyze(&NixAnalyzer::new().with_threshold(1), source, "flake.nix");

        assert!(metrics.complexity.functions[0].is_test);
        assert!(metrics.debt_items.is_empty());
    }

    #[test]
    fn test_generated_file_suppresses_debt() {
        let source = "# generated by node2nix\n{ f = a: if a then 1 else 2; }";
        let metrics = analyze(&NixAnalyzer::new().with_threshold(1), source, "x.nix");

        assert_eq!(metrics.complexity.functions.len(), 1);
        assert!(metrics.debt_items.is_empty());
    }

    #[test]
    fn test_generated_file_analyze_mode_emits_debt() {
        let analyzer = NixAnalyzer::new()
            .with_threshold(1)
            .with_generated_code_mode(GeneratedCodeMode::Analyze);
        let source = "# generated by node2nix\n{ f = a: if a then 1 else 2; }";

        assert!(!analyze(&analyzer, source, "x.nix").debt_items.is_empty());
    }
}
