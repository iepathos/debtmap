//! Compact per-commit facts for recent-activity analysis.
//!
//! Commit messages are reduced to what churn analysis needs: whether the
//! commit is a fix or a revert (and which commit it reverts), its
//! conventional-commit scope, and the lines that may name an AI agent
//! (`Co-authored-by:` trailers and "Generated with/by" footers). Deciding
//! which agents count as LLMs is left to the consumer.

use super::git2_provider::is_bug_fix_message;
use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

/// One commit that touched a function.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CommitFact {
    pub hash: String,
    pub date: DateTime<Utc>,
    pub fix: bool,
    pub revert: bool,
    /// Hash from a `This reverts commit <hash>.` line, as written (may be abbreviated).
    pub reverted_hash: Option<String>,
    /// Lowercased conventional-commit scope, e.g. `parser` in `fix(parser): ...`.
    pub scope: Option<String>,
    /// Lowercased trailer values and footer lines that may identify an agent.
    pub agent_marks: Vec<String>,
}

/// Commits that touched a function, oldest first, plus repo-wide fix dates
/// for the conventional-commit scopes those commits used.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct CommitActivity {
    pub commits: Vec<CommitFact>,
    pub scope_fixes: BTreeMap<String, Vec<DateTime<Utc>>>,
    /// Repo-wide dates of scope-less conventional fixes (`fix: ...`) that
    /// touched this function's file, oldest first.
    #[serde(default)]
    pub file_fixes: Vec<DateTime<Utc>>,
}

impl CommitActivity {
    pub fn scopes(&self) -> impl Iterator<Item = &str> {
        self.commits.iter().filter_map(|c| c.scope.as_deref())
    }
}

pub fn commit_fact(hash: &str, date: DateTime<Utc>, message: &str) -> CommitFact {
    let reverted_hash = reverted_hash(message);
    CommitFact {
        hash: hash.to_string(),
        date,
        fix: is_bug_fix_message(message),
        revert: reverted_hash.is_some() || is_revert_subject(message),
        reverted_hash,
        scope: conventional_scope(message),
        agent_marks: agent_marks(message),
    }
}

impl CommitFact {
    /// Whether this commit reverts `other`, by full or abbreviated hash.
    pub fn reverts(&self, other: &CommitFact) -> bool {
        self.reverted_hash
            .as_deref()
            .is_some_and(|h| !other.hash.is_empty() && other.hash.starts_with(h))
    }
}

/// `git revert` subjects (`Revert "..."`) and conventional `revert:` commits.
fn is_revert_subject(message: &str) -> bool {
    let subject = message.lines().next().unwrap_or_default().trim();
    subject.starts_with("Revert \"")
        || git_conventional::Commit::parse(message.trim())
            .is_ok_and(|c| c.type_() == git_conventional::Type::REVERT)
}

/// Hash from the `This reverts commit <hash>.` line `git revert` writes.
fn reverted_hash(message: &str) -> Option<String> {
    message.lines().find_map(|line| {
        let hash = line
            .trim()
            .strip_prefix("This reverts commit ")?
            .trim_end_matches(['.', ',']);
        let valid = hash.len() >= 7 && hash.chars().all(|c| c.is_ascii_hexdigit());
        valid.then(|| hash.to_lowercase())
    })
}

/// For a conventional `fix` commit, its lowercased scope: `Some(None)` for
/// `fix: ...`, `Some(Some("parser"))` for `fix(parser): ...`.
pub fn conventional_fix_scope(message: &str) -> Option<Option<String>> {
    let commit = git_conventional::Commit::parse(message.trim()).ok()?;
    (commit.type_() == git_conventional::Type::FIX)
        .then(|| commit.scope().map(|s| s.to_lowercase()))
}

fn conventional_scope(message: &str) -> Option<String> {
    let commit = git_conventional::Commit::parse(message.trim()).ok()?;
    commit.scope().map(|s| s.to_lowercase())
}

/// `Co-authored-by` trailer values plus "Generated with/by" footer lines,
/// which tools such as Claude Code add outside the trailer block.
fn agent_marks(message: &str) -> Vec<String> {
    let footers = message
        .lines()
        .map(|line| line.trim().to_lowercase())
        .filter(|line| line.contains("generated with") || line.contains("generated by"));
    let co_authors = git2::message_trailers_strs(message)
        .map(|trailers| {
            trailers
                .iter()
                .filter(|(key, _)| key.eq_ignore_ascii_case("co-authored-by"))
                .map(|(_, value)| value.trim().to_lowercase())
                .collect::<Vec<_>>()
        })
        .unwrap_or_default();
    footers.chain(co_authors).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn now() -> DateTime<Utc> {
        DateTime::parse_from_rfc3339("2026-10-01T00:00:00Z")
            .unwrap()
            .with_timezone(&Utc)
    }

    #[test]
    fn extracts_co_author_trailers_and_generated_footers() {
        let fact = commit_fact(
            "a1",
            now(),
            "feat(parser): add tokens\n\n🤖 Generated with [Claude Code](https://claude.com)\n\n\
             Co-Authored-By: Claude <noreply@anthropic.com>\nco-authored-by: Bob <bob@x.org>",
        );
        assert_eq!(
            fact.agent_marks,
            [
                "🤖 generated with [claude code](https://claude.com)",
                "claude <noreply@anthropic.com>",
                "bob <bob@x.org>",
            ]
        );
        assert_eq!(fact.scope.as_deref(), Some("parser"));
        assert!(!fact.fix);
    }

    #[test]
    fn parses_conventional_fix_scopes() {
        let scoped = |s: &str| Some(Some(s.to_string()));
        assert_eq!(
            conventional_fix_scope("fix(Parser): off by one"),
            scoped("parser")
        );
        assert_eq!(conventional_fix_scope("fix(api)!: break it"), scoped("api"));
        assert_eq!(conventional_fix_scope("fix: no scope"), Some(None));
        assert_eq!(conventional_fix_scope("feat(api): not a fix"), None);
        assert_eq!(conventional_fix_scope("fixup(api): nope"), None);
        assert!(commit_fact("a1", now(), "fix(api): crash").fix);
    }

    #[test]
    fn plain_messages_have_no_scope_or_marks() {
        let fact = commit_fact("a1", now(), "Update readme (again)");
        assert_eq!(fact.scope, None);
        assert!(fact.agent_marks.is_empty());
        assert!(!fact.revert);
    }

    #[test]
    fn detects_git_reverts_and_their_target() {
        let target = commit_fact("abcdef0123456789", now(), "feat: risky change");
        let revert = commit_fact(
            "f00d",
            now(),
            "Revert \"feat: risky change\"\n\nThis reverts commit abcdef0123.",
        );
        assert!(revert.revert);
        assert_eq!(revert.reverted_hash.as_deref(), Some("abcdef0123"));
        assert!(revert.reverts(&target));
        assert!(!target.reverts(&revert));
    }

    #[test]
    fn detects_conventional_reverts_without_a_hash() {
        let revert = commit_fact("f00d", now(), "revert(parser): back out tab support");
        assert!(revert.revert);
        assert_eq!(revert.reverted_hash, None);
        assert_eq!(revert.scope.as_deref(), Some("parser"));
        assert!(!commit_fact("f00d", now(), "Reverted to old wording").revert);
    }
}
